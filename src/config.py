def get_command_texts(key: str) -> dict[str, str]:
    """Возвращает словарь текстов команд по ключу."""
    _HELP_COMMANDS: dict[str, str] = {
        "Мой крад": "— посмотреть своего крада",
        "Меню": "— открыть игровое меню",
        "Бой": "— начать бой с монстром",
        "Экспедиция": "— отправиться в экспедицию",
        "Сменить имя": "— изменить имя крада",
        "Сменить пол": "— сменить пол крада",
        "Крад инфо": "— информация о краде",
        "Крад класс": "— выбрать класс крада",
        "Топ": "— рейтинг игроков",
        "Помощь": "— эта справка",
        "Админ": "— команды разработчика",
    }
    _HELP_ADVENTURE: dict[str, str] = {
        "!поход": "— отправиться в генеративный поход",
        "!статус": "— проверить текущий поход",
        "!вернуться": "— вернуться из похода или отменить выбор",
        "!выбор": "— выбрать событие (используйте цифру)",
    }
    if key == "help_commands":
        return _HELP_COMMANDS
    if key == "adventure":
        return _HELP_ADVENTURE
    return {}
